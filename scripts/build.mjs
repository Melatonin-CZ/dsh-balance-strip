// 构建：把纯函数层 + 客户端层拼成宿主要求的 ModuleLoader 形态；宿主入口原样拷到 lib。
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (p) => readFileSync(join(root, p), 'utf8')

const PLUGIN_ID = 'dsh-balance-strip'
const core = read('src/shared/core.cjs')
const client = read('src/client/main.cjs')

const banner = `/* ${PLUGIN_ID} — generated by scripts/build.mjs, do not edit. */`
const bundle = `${banner}
window.__ModuleLoader__.load({ id: "${PLUGIN_ID}", factory: (require) => {
var module = { exports: {} }; var exports = module.exports;
/* ---- src/shared/core.cjs ---- */
${core}
/* ---- 交接：core 导出供客户端层使用 ---- */
var core = module.exports;
module.exports = {}; exports = module.exports;
/* ---- src/client/main.cjs ---- */
${client}
return module.exports; } });
`

mkdirSync(join(root, 'lib/shared'), { recursive: true })
writeFileSync(join(root, 'lib/client.js'), bundle, 'utf8')
copyFileSync(join(root, 'src/index.js'), join(root, 'lib/index.js'))
copyFileSync(join(root, 'src/shared/core.cjs'), join(root, 'lib/shared/core.cjs'))

console.log(`built: lib/client.js (${bundle.length} B) · lib/index.js · lib/shared/core.cjs`)
